import UIKit

/// Shared colors. The window, the web view and the launch screen
/// (LaunchBackground.colorset) all use #070a19 so nothing flashes between them.
enum Theme {
    static let background: UIColor = UIColor(
        red: 7.0 / 255.0,
        green: 10.0 / 255.0,
        blue: 25.0 / 255.0,
        alpha: 1.0
    )
}
