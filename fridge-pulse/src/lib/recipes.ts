import type { Role } from './ingredients';

/**
 * The built-in recipe library: offline ideas that need no AI and no network.
 *
 * Each recipe lists the kinds of food it needs (`needs`, all required) and can use (`optional`), by
 * culinary role (see `src/lib/ingredients.ts`), never by name or category. Steps and extras can be
 * conditional on what was used, and `{key}` in a line becomes the names of the foods in that slot,
 * so the steps describe the actual meal ("Soften the bell peppers and spinach").
 *
 * `__tests__/recipes.test.ts` checks every recipe: sweet things never go into savoury dishes, savoury
 * things never into desserts, every recipe can be made, every placeholder and condition resolves.
 */

export type Course = 'breakfast' | 'main' | 'side' | 'snack' | 'dessert' | 'drink';

export interface Slot {
  /** Names the slot for `{key}` placeholders and conditions. */
  key: string;
  /** Any of these roles fills the slot. */
  roles: Role[];
  /** Distinct foods needed (default 1). */
  min?: number;
  /** Most foods used (default 1). */
  max?: number;
  /** Frozen food will not do (fruit for dipping, a raw salad). */
  fresh?: boolean;
}

/**
 * A slot key ("cheese": the slot was filled) or a role with "@" ("@cooked-rice": something used
 * filled its slot as that role). A list matches if any entry does.
 */
export type Cond = string | string[];
export type Line = string | { if?: Cond; unless?: Cond; text: string };

export interface Recipe {
  id: string;
  title: string;
  course: Course;
  /** Ideas from one family are spread out so the list is not five pastas. */
  family: string;
  taste: 'savory' | 'sweet';
  summary: string;
  minutes: number;
  needs: Slot[];
  /** At least one of these must be filled (each is filled if it can be): "eggs or a protein". */
  anyOf?: Slot[];
  optional?: Slot[];
  extras: Line[];
  steps: Line[];
}

function s(key: string, roles: Role[], max = 1, min = 1): Slot {
  return { key, roles, max, min };
}
const fresh = (slot: Slot): Slot => ({ ...slot, fresh: true });

